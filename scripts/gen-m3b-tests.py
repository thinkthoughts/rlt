"""Write the RLT-003 M3b test proofs into tests/m3b/ (untrusted generator).

usage: scripts/gen-m3b-tests.py RLT_BINARY OUT_DIR

Accepted proofs go to OUT_DIR/accept, rejected and malformed ones to
OUT_DIR/reject, and OUT_DIR/expected.tsv lists every rejected file with its
required exit code and a substring its verdict must contain. Arithmetic
pieces come from `rlt gen`; the kernel checks every step either way.
verify.sh regenerates this directory and requires it to match. Cases that
need a scratch repository or the kernel API run in cli/tests/m3b.rs.
"""
