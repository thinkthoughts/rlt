rlt, out = sys.argv[1], sys.argv[2]


def gen_steps(equation, prefix):
    """Steps of an `rlt gen` proof, relabelled with a prefix; returns (steps, last label)."""
    text = subprocess.run([rlt, "gen", equation, "X"], check=True,
                          capture_output=True, text=True).stdout
    body = text[text.index("(steps") + len("(steps"):].rstrip()
    assert body.endswith("))"), "unexpected rlt gen output"
    body = body[:-2]
    lines = [l.strip() for l in body.strip().splitlines() if l.strip()]
    relabel = lambda s: re.sub(r"\bs(\d+)\b", lambda m: f"{prefix}{m.group(1)}", s)
    lines = [relabel(l) for l in lines]
    last = re.match(r"\((\S+)", lines[-1]).group(1)
    return lines, last


def proof(pid, goal, steps, axioms="ROBINSON-Q", params="", extra="",
          mode="unconditional", convention="NAT-DEF"):
    p = f"  (params {params})\n" if params else ""
    body = "\n".join("    " + s for s in steps)
    return (f"; RLT-003 M3b test {pid}. Generated by scripts/gen-m3b-tests.py.\n"
            f"(rlt-proof\n  (id M3b.{pid})\n  (convention {convention})\n  (goal \"{goal}\")\n"
            f"  (mode {mode})\n{extra}  (axioms {axioms})\n{p}  (steps\n{body}))\n")


def succ_eq(t, pre):
    """Steps proving t + 1 = S(t) for a term t (proof syntax); returns (steps, label)."""
    return [
        f"({pre}1 (= (+ {t} 1) (S (+ {t} 0))) (inst add_succ (x {t}) (y 0)))",
        f"({pre}2 (= (+ {t} 0) {t}) (inst add_zero (x {t})))",
        f"({pre}3 (= (S (+ {t} 0)) (S {t})) (cong S {pre}2))",
        f"({pre}4 (= (+ {t} 1) (S {t})) (trans {pre}1 {pre}3))",
    ], f"{pre}4"


