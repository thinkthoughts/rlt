def gen_steps(equation, prefix):
    """Steps of an `rlt gen` proof, relabelled with a prefix; returns (steps, last label)."""
    text = subprocess.run([rlt, "gen", equation, "X"], check=True,
                          capture_output=True, text=True).stdout
    body = text[text.index("(steps") + len("(steps"):].rstrip()
    assert body.endswith("))"), "unexpected rlt gen output"
    body = body[:-2]  # the closing parentheses of (steps …) and (rlt-proof …)
    lines = [l.strip() for l in body.strip().splitlines() if l.strip()]
    relabel = lambda s: re.sub(r"\bs(\d+)\b", lambda m: f"{prefix}{m.group(1)}", s)
    lines = [relabel(l) for l in lines]
    last = re.match(r"\((\S+)", lines[-1]).group(1)
    return lines, last


def proof(pid, goal, steps, axioms="PEANO-ADD", params="", extra="", mode="unconditional"):
    p = f"  (params {params})\n" if params else ""
    body = "\n".join("    " + s for s in steps)
    return (f"; RLT-003 M3a test {pid}. Generated by scripts/gen-m3a-tests.py.\n"
            f"(rlt-proof\n  (id M3a.{pid})\n  (convention NAT-LOGIC)\n  (goal \"{goal}\")\n"
            f"  (mode {mode})\n{extra}  (axioms {axioms})\n{p}  (steps\n{body}))\n")


